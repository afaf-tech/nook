//! Parity measurement: the Navicat feature catalog against the live command registry.
//! The checklist is generated (`nook-cli parity --markdown`), and a test keeps the floor rising.

use crate::catalog::{catalog, CatalogEntry};
use crate::registry;

/// One area's coverage.
#[derive(Debug, Clone, PartialEq)]
pub struct AreaCoverage {
    pub area: String,
    pub covered: usize,
    pub total: usize,
}

impl AreaCoverage {
    pub fn percent(&self) -> f64 {
        if self.total == 0 {
            100.0
        } else {
            self.covered as f64 * 100.0 / self.total as f64
        }
    }
}

#[derive(Debug, Clone, PartialEq, Default)]
pub struct ParityReport {
    pub covered: Vec<&'static str>,
    pub missing: Vec<&'static str>,
    /// Commands that no catalog entry describes: extras beyond Navicat.
    pub extra: Vec<&'static str>,
    pub by_area: Vec<AreaCoverage>,
}

impl ParityReport {
    pub fn total(&self) -> usize {
        self.covered.len() + self.missing.len()
    }

    pub fn percent(&self) -> f64 {
        if self.total() == 0 {
            100.0
        } else {
            self.covered.len() as f64 * 100.0 / self.total() as f64
        }
    }

    pub fn summary(&self) -> String {
        format!(
            "{}/{} catalog features have commands ({:.1}%) · {} commands beyond the catalog",
            self.covered.len(),
            self.total(),
            self.percent(),
            self.extra.len()
        )
    }

    pub fn missing_by_area(&self) -> Vec<(String, Vec<&'static str>)> {
        let mut out: Vec<(String, Vec<&'static str>)> = Vec::new();
        for entry in catalog() {
            if !self.missing.contains(&entry.id) {
                continue;
            }
            match out.iter_mut().find(|(area, _)| area == entry.area) {
                Some((_, list)) => list.push(entry.id),
                None => out.push((entry.area.to_string(), vec![entry.id])),
            }
        }
        out
    }

    /// The rising floor used by the test suite: coverage may never drop below this.
    pub fn floor_percent() -> f64 {
        55.0
    }

    pub fn markdown(&self) -> String {
        let mut out = String::new();
        out.push_str("# Nook feature parity\n\n");
        out.push_str("Generated by `nook-cli parity --markdown`: the Navicat feature catalog\n");
        out.push_str(
            "(`crates/engine/src/catalog.rs`) compared with the live command registry.\n\n",
        );
        out.push_str(&format!("**{}**\n\n", self.summary()));
        out.push_str("| Area | Covered | Total | Coverage |\n|---|---|---|---|\n");
        for area in &self.by_area {
            out.push_str(&format!(
                "| {} | {} | {} | {:.0}% |\n",
                area.area,
                area.covered,
                area.total,
                area.percent()
            ));
        }
        out.push_str("\n## Not implemented yet\n\n");
        for (area, ids) in self.missing_by_area() {
            out.push_str(&format!("### {area}\n\n"));
            for id in ids {
                let entry: Option<&CatalogEntry> = catalog().iter().find(|e| e.id == id);
                match entry {
                    Some(e) => out.push_str(&format!("- {} (`{}`) — {}\n", e.label, e.id, e.note)),
                    None => out.push_str(&format!("- `{id}`\n")),
                }
            }
            out.push('\n');
        }
        out.push_str("## Beyond the catalog\n\n");
        if self.extra.is_empty() {
            out.push_str("Every command is described by a catalog entry.\n");
        } else {
            for id in &self.extra {
                out.push_str(&format!("- `{id}`\n"));
            }
        }
        out
    }
}

pub fn measure() -> ParityReport {
    let command_ids: Vec<&'static str> = registry().iter().map(|c| c.id).collect();
    let mut report = ParityReport::default();
    for entry in catalog() {
        if command_ids.contains(&entry.id) {
            report.covered.push(entry.id);
        } else {
            report.missing.push(entry.id);
        }
    }
    report.extra = command_ids
        .iter()
        .copied()
        .filter(|id| !catalog().iter().any(|e| e.id == *id))
        .collect();
    let mut areas: Vec<String> = catalog().iter().map(|e| e.area.to_string()).collect();
    areas.sort();
    areas.dedup();
    for area in areas {
        let total = catalog().iter().filter(|e| e.area == area).count();
        let covered = catalog()
            .iter()
            .filter(|e| e.area == area && command_ids.contains(&e.id))
            .count();
        report.by_area.push(AreaCoverage {
            area,
            covered,
            total,
        });
    }
    report
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn coverage_never_drops_below_the_floor() {
        let report = measure();
        assert!(
            report.percent() >= ParityReport::floor_percent(),
            "parity fell to {:.1}%: {}\nmissing: {:?}",
            report.percent(),
            report.summary(),
            report.missing
        );
    }

    #[test]
    fn every_missing_entry_explains_itself() {
        let report = measure();
        for id in &report.missing {
            let entry = catalog()
                .iter()
                .find(|e| e.id == *id)
                .expect("catalog entry");
            assert!(
                !entry.note.trim().is_empty(),
                "missing feature {} has no note",
                entry.id
            );
        }
    }

    #[test]
    fn area_totals_add_up() {
        let report = measure();
        let sum: usize = report.by_area.iter().map(|a| a.total).sum();
        assert_eq!(sum, report.total());
        assert!(report.by_area.iter().all(|a| a.covered <= a.total));
    }

    #[test]
    fn markdown_lists_areas_and_gaps() {
        let report = measure();
        let md = report.markdown();
        assert!(md.contains("| Area | Covered | Total | Coverage |"));
        assert!(md.contains("## Not implemented yet"));
        assert!(md.contains("MongoDB connection"));
    }
}
